export type TKey = keyof (typeof dict)['ru']

type Ctx = {
  locale: Locale
  setLocale: (l: Locale) => void
  t: (k: TKey) => string
}
const I18nContext = createContext<Ctx | null>(null)

const STORAGE_KEY = 'auksion.locale'

function initialLocale(): Locale {
  try {
    const saved = localStorage.getItem(STORAGE_KEY)
    if (saved === 'ru' || saved === 'uz') return saved
  } catch {
    // localStorage недоступен — используем язык браузера
  }
  // язык браузера: узбекский — если он стоит первым, иначе русский
  return navigator.language?.toLowerCase().startsWith('uz') ? 'uz' : 'ru'
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(initialLocale)
  const value = useMemo<Ctx>(
    () => ({
      locale,
      setLocale: (l) => {
        setLocaleState(l)
        try {
          localStorage.setItem(STORAGE_KEY, l)
        } catch {
          // не критично
        }
      },
      t: (k) => dict[locale][k],
    }),
    [locale]
  )
  return <I18nContext value={value}>{children}</I18nContext>
}

export function useI18n(): Ctx {
  const ctx = useContext(I18nContext)
  if (!ctx) throw new Error('useI18n outside I18nProvider')
  return ctx
}
